#!/usr/bin/env node
"use strict";
const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
const optimizedRoot = path.join(root, "third_party", "heroicons", "optimized");
const outputPath = path.join(root, "src", "shared", "icons.js");
const variants = Object.freeze([
  Object.freeze({ key: "24-outline", label: "24px Outline", source: "24/outline" }),
  Object.freeze({ key: "24-solid", label: "24px Solid", source: "24/solid" }),
  Object.freeze({ key: "20-solid", label: "20px Solid", source: "20/solid" }),
  Object.freeze({ key: "16-solid", label: "16px Solid", source: "16/solid" })
]);
const legacyAliases = Object.freeze({
  pin: "24-outline/map-pin",
  home: "24-outline/home",
  tower: "24-outline/building-office-2",
  launch: "24-outline/rocket-launch",
  landing: "24-outline/arrow-down-on-square",
  star: "24-outline/star",
  warning: "24-outline/exclamation-triangle",
  vehicle: "24-outline/truck",
  flag: "24-outline/flag",
  signal: "24-outline/signal",
  airplane: "24-outline/paper-airplane",
  camera: "24-outline/camera",
  fire: "24-outline/fire",
  tools: "24-outline/wrench-screwdriver",
  recovery: "24-outline/lifebuoy",
  person: "24-outline/user",
  cloud: "24-outline/cloud",
  info: "24-outline/information-circle",
  lightning: "24-outline/bolt",
  science: "24-outline/beaker",
  globe: "24-outline/globe-alt",
  search: "24-outline/magnifying-glass",
  map: "24-outline/map",
  radio: "24-outline/radio"
});

function labelFor(name) {
  return name.split("-").map((word) => (/^\d+$/.test(word) ? word : `${word[0].toUpperCase()}${word.slice(1)}`)).join(" ");
}

function readVariant(variant) {
  const sourceDir = path.join(optimizedRoot, variant.source);
  const files = fs.readdirSync(sourceDir, { withFileTypes: true })
    .filter((entry) => entry.isFile() && entry.name.endsWith(".svg"))
    .map((entry) => entry.name)
    .sort();
  if (!files.length) throw new Error(`No Heroicons found in ${sourceDir}`);
  return files.map((file) => {
    const name = file.slice(0, -4);
    const svg = fs.readFileSync(path.join(sourceDir, file), "utf8");
    if (!svg.startsWith("<svg ") || !svg.endsWith("\n")) throw new Error(`Unexpected SVG source: ${variant.source}/${file}`);
    return `    Object.freeze({ key: ${JSON.stringify(`${variant.key}/${name}`)}, name: ${JSON.stringify(name)}, label: ${JSON.stringify(labelFor(name))}, style: ${JSON.stringify(variant.key)}, styleLabel: ${JSON.stringify(variant.label)}, svg: ${JSON.stringify(svg)} }),`;
  });
}

const catalog = variants.flatMap(readVariant);
const source = [
  "/* Generated by scripts/generate-icon-catalog.js from the complete vendored Heroicons catalog. Do not edit manually. */",
  "(function exposeIcons(root, factory) {",
  "  const api = factory();",
  "  if (typeof module === \"object\" && module.exports) module.exports = api;",
  "  root.SondeHubIcons = api;",
  "})(typeof globalThis !== \"undefined\" ? globalThis : this, function iconsFactory() {",
  "  \"use strict\";",
  "",
  `  const STYLES = Object.freeze(${JSON.stringify(variants.map(({ key, label }) => ({ key, label })), null, 2)}.map(Object.freeze));`,
  "  const ICONS = Object.freeze([",
  catalog.join("\n"),
  "  ]);",
  "  const DEFAULT_ICON = \"24-outline/map-pin\";",
  `  const LEGACY_ALIASES = Object.freeze(${JSON.stringify(legacyAliases, null, 2)});`,
  "  const ICON_BY_KEY = Object.freeze(Object.fromEntries(ICONS.map((icon) => [icon.key, icon])));",
  "  const OUTLINE_BY_NAME = Object.freeze(Object.fromEntries(ICONS.filter((icon) => icon.style === \"24-outline\").map((icon) => [icon.name, icon.key])));",
  "  const STYLE_BY_KEY = Object.freeze(Object.fromEntries(STYLES.map((style) => [style.key, style])));",
  "",
  "  function normalizeText(value) {",
  "    return String(value == null ? \"\" : value).trim().toLowerCase().replace(/[\\/_-]+/g, \" \").replace(/\\s+/g, \" \").trim();",
  "  }",
  "  function normalizeIcon(icon) {",
  "    const key = String(icon == null ? \"\" : icon).trim().toLowerCase();",
  "    if (Object.hasOwn(ICON_BY_KEY, key)) return key;",
  "    if (Object.hasOwn(LEGACY_ALIASES, key)) return LEGACY_ALIASES[key];",
  "    if (Object.hasOwn(OUTLINE_BY_NAME, key)) return OUTLINE_BY_NAME[key];",
  "    return DEFAULT_ICON;",
  "  }",
  "  function canonicalIconKey(icon) { return normalizeIcon(icon); }",
  "  function iconFor(icon) { return ICON_BY_KEY[canonicalIconKey(icon)]; }",
  "  function filterIcons(query, style) {",
  "    const needle = normalizeText(query);",
  "    const selectedStyle = String(style == null ? \"\" : style).trim();",
  "    const pool = Object.hasOwn(STYLE_BY_KEY, selectedStyle) ? ICONS.filter((icon) => icon.style === selectedStyle) : ICONS;",
  "    if (!needle) return pool;",
  "    return pool.filter((icon) => normalizeText(`${icon.name} ${icon.label} ${icon.styleLabel}`).includes(needle));",
  "  }",
  "  function svgFor(icon) { return iconFor(icon).svg.replace(\"<svg \", '<svg style=\"width:18px;height:18px;display:block\" '); }",
  "",
  "  return Object.freeze({ DEFAULT_ICON, STYLES, ICONS, LEGACY_ALIASES, normalizeIcon, canonicalIconKey, iconFor, filterIcons, svgFor });",
  "});",
  ""
].join("\n");

if (process.argv.includes("--check")) {
  if (fs.readFileSync(outputPath, "utf8") !== source) throw new Error("src/shared/icons.js is not generated from the complete vendored Heroicons catalog; run npm run generate:icons");
  console.log(`Verified ${path.relative(root, outputPath)} matches ${catalog.length} vendored Heroicons variants.`);
} else {
  fs.writeFileSync(outputPath, source);
  console.log(`Generated ${path.relative(root, outputPath)} from ${catalog.length} Heroicons variants.`);
}
