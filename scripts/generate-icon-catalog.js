#!/usr/bin/env node
"use strict";
const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
const sourceDir = path.join(root, "third_party", "heroicons", "optimized", "16", "solid");
const outputPath = path.join(root, "src", "shared", "icons.js");
const style = Object.freeze({ key: "16-solid", label: "16px Micro" });
const legacyAliases = Object.freeze({
  pin: "16-solid/map-pin",
  home: "16-solid/home",
  tower: "16-solid/building-office-2",
  launch: "16-solid/rocket-launch",
  landing: "16-solid/arrow-down-on-square",
  star: "16-solid/star",
  warning: "16-solid/exclamation-triangle",
  vehicle: "16-solid/truck",
  flag: "16-solid/flag",
  signal: "16-solid/signal",
  airplane: "16-solid/paper-airplane",
  camera: "16-solid/camera",
  fire: "16-solid/fire",
  tools: "16-solid/wrench-screwdriver",
  recovery: "16-solid/lifebuoy",
  person: "16-solid/user",
  cloud: "16-solid/cloud",
  info: "16-solid/information-circle",
  lightning: "16-solid/bolt",
  science: "16-solid/beaker",
  globe: "16-solid/globe-alt",
  search: "16-solid/magnifying-glass",
  map: "16-solid/map",
  radio: "16-solid/radio"
});

function labelFor(name) {
  return name.split("-").map((word) => (/^\d+$/.test(word) ? word : `${word[0].toUpperCase()}${word.slice(1)}`)).join(" ");
}

const files = fs.readdirSync(sourceDir, { withFileTypes: true })
  .filter((entry) => entry.isFile() && entry.name.endsWith(".svg"))
  .map((entry) => entry.name)
  .sort();
if (!files.length) throw new Error(`No Heroicons Micro icons found in ${sourceDir}`);

const catalog = files.map((file) => {
  const name = file.slice(0, -4);
  const svg = fs.readFileSync(path.join(sourceDir, file), "utf8");
  if (!svg.startsWith("<svg ") || !svg.endsWith("\n")) throw new Error(`Unexpected SVG source: 16/solid/${file}`);
  return `    Object.freeze({ key: ${JSON.stringify(`16-solid/${name}`)}, name: ${JSON.stringify(name)}, label: ${JSON.stringify(labelFor(name))}, style: ${JSON.stringify(style.key)}, styleLabel: ${JSON.stringify(style.label)}, svg: ${JSON.stringify(svg)} }),`;
});

const source = [
  "/* Generated by scripts/generate-icon-catalog.js from the vendored Heroicons Micro catalog. Do not edit manually. */",
  "(function exposeIcons(root, factory) {",
  "  const api = factory();",
  "  if (typeof module === \"object\" && module.exports) module.exports = api;",
  "  root.SondeHubIcons = api;",
  "})(typeof globalThis !== \"undefined\" ? globalThis : this, function iconsFactory() {",
  "  \"use strict\";",
  "",
  `  const STYLES = Object.freeze([Object.freeze(${JSON.stringify(style)})]);`,
  "  const ICONS = Object.freeze([",
  catalog.join("\n"),
  "  ]);",
  "  const DEFAULT_ICON = \"16-solid/map-pin\";",
  `  const LEGACY_ALIASES = Object.freeze(${JSON.stringify(legacyAliases, null, 2)});`,
  "  const ICON_BY_KEY = Object.freeze(Object.fromEntries(ICONS.map((icon) => [icon.key, icon])));",
  "  const MICRO_BY_NAME = Object.freeze(Object.fromEntries(ICONS.map((icon) => [icon.name, icon.key])));",
  "",
  "  function normalizeText(value) {",
  "    return String(value == null ? \"\" : value).trim().toLowerCase().replace(/[\\/_-]+/g, \" \").replace(/\\s+/g, \" \").trim();",
  "  }",
  "  function normalizeIcon(icon) {",
  "    const key = String(icon == null ? \"\" : icon).trim().toLowerCase();",
  "    if (Object.hasOwn(ICON_BY_KEY, key)) return key;",
  "    if (Object.hasOwn(LEGACY_ALIASES, key)) return LEGACY_ALIASES[key];",
  "    const previousVariant = key.match(/^(?:16|20|24)-(?:outline|solid)\\/(.+)$/);",
  "    if (previousVariant && Object.hasOwn(MICRO_BY_NAME, previousVariant[1])) return MICRO_BY_NAME[previousVariant[1]];",
  "    if (Object.hasOwn(MICRO_BY_NAME, key)) return MICRO_BY_NAME[key];",
  "    return DEFAULT_ICON;",
  "  }",
  "  function canonicalIconKey(icon) { return normalizeIcon(icon); }",
  "  function iconFor(icon) { return ICON_BY_KEY[canonicalIconKey(icon)]; }",
  "  function filterIcons(query) {",
  "    const needle = normalizeText(query);",
  "    if (!needle) return ICONS;",
  "    return ICONS.filter((icon) => normalizeText(`${icon.name} ${icon.label}`).includes(needle));",
  "  }",
  "  function svgFor(icon) { return iconFor(icon).svg.replace(\"<svg \", '<svg style=\"width:16px;height:16px;display:block\" '); }",
  "",
  "  return Object.freeze({ DEFAULT_ICON, STYLES, ICONS, LEGACY_ALIASES, normalizeIcon, canonicalIconKey, iconFor, filterIcons, svgFor });",
  "});",
  ""
].join("\n");

if (process.argv.includes("--check")) {
  if (fs.readFileSync(outputPath, "utf8") !== source) throw new Error("src/shared/icons.js is not generated from the vendored Heroicons Micro catalog; run npm run generate:icons");
  console.log(`Verified ${path.relative(root, outputPath)} matches ${catalog.length} vendored Heroicons Micro icons.`);
} else {
  fs.writeFileSync(outputPath, source);
  console.log(`Generated ${path.relative(root, outputPath)} from ${catalog.length} Heroicons Micro icons.`);
}
